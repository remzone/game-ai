/** Give an existing identity a name without changing the simulation or its RNG. */
export function organicPersonName(
  world: Pick<World, 'seed'>,
  person: Pick<Person, 'id' | 'sex' | 'ancestry'>,
) {
  const catalog = names[dominantRace(person)];
  const given = catalog[person.sex];
  const base = `${world.seed}:name:${person.id}`;
  return `${given[seedHash(base + ':given') % given.length]} ${catalog.families[seedHash(base + ':family') % catalog.families.length]}`;
}
